#!/usr/bin/env node
/**
 * Pre-deploy + pre-build sync for Stage 3 Cloud Functions.
 *
 * Cross-package imports don't work for `firebase deploy --only functions`
 * because the functions/ directory is deployed as its own npm package
 * with its own node_modules. Root-level scripts/pre-process/*.ts files
 * that contain Function-used logic (drive-poller, drive-mirror,
 * alert-on-failure) can't be imported from functions/src/ at runtime.
 *
 * This script copies the needed shared modules into functions/src/shared/
 * and rewrites their firebase-admin imports to use the functions/-local
 * copy of the package, so the compiled tsc output resolves correctly
 * inside the deployed Function runtime.
 *
 * It runs automatically before `pnpm build` + `pnpm deploy` via the
 * "prebuild" npm lifecycle hook in functions/package.json.
 *
 * Source of truth stays in scripts/pre-process/ — this sync is
 * one-way. Edits to functions/src/shared/** are overwritten on
 * every deploy.
 */

import { readdirSync, readFileSync, writeFileSync, mkdirSync, rmSync, existsSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const __dirname = dirname(fileURLToPath(import.meta.url))
const FUNCTIONS_ROOT = resolve(__dirname, '..')
const REPO_ROOT = resolve(FUNCTIONS_ROOT, '..')
const SRC_ROOT = join(REPO_ROOT, 'scripts', 'pre-process')
const DEST_ROOT = join(FUNCTIONS_ROOT, 'src', 'shared')

// Modules used at Cloud-Function runtime. `run-recorder.ts` is
// intentionally NOT here — only the preprocess CLI (which runs in
// GH Actions via pnpm, not in Functions) writes pipeline_runs.
const MODULES_TO_COPY = [
  'drive-state.ts',
  'drive-poller.ts',
  'drive-mirror.ts',
  'alert-on-failure.ts',
  'drive-auth-monitor.ts',
]

function rewriteImports(content) {
  // Strip any `@/lib/data/*` imports that only export types — the
  // shared modules avoid value imports across this boundary, so
  // type-only imports can be left pointing at a local .d.ts shim
  // or inlined. For now we rewrite `@/lib/data/types` to a relative
  // path that resolves to the copied shim.
  let out = content
  out = out.replace(/from '@\/lib\/data\/types'/g, "from './lib-data-types'")
  return out
}

function copyFileWithRewrite(srcPath, destPath) {
  const content = readFileSync(srcPath, 'utf-8')
  const rewritten = rewriteImports(content)
  const banner =
    '// AUTO-GENERATED by functions/scripts/sync-shared.mjs — do not edit.\n' +
    `// Source: scripts/pre-process/${srcPath.split('/').pop()}\n\n`
  writeFileSync(destPath, banner + rewritten, 'utf-8')
}

function copyLibDataTypesShim() {
  // Inline the minimal slice of src/lib/data/types.ts that the shared
  // modules reference. Kept narrow on purpose — widen only if a sync
  // error surfaces.
  const shim = `// AUTO-GENERATED by functions/scripts/sync-shared.mjs — do not edit.
// Narrow slice of src/lib/data/types.ts for Cloud-Functions use.

import type { Timestamp } from 'firebase-admin/firestore'

export type SiteId = 'placencia' | 'caye-caulker' | 'laughing-bird'
export type DatasetScope = 'site' | 'multi-site' | 'national'
export type PipelineRunStatus = 'running' | 'success' | 'partial' | 'failed'
export type DatasetOutcomeStatus =
  | 'published'
  | 'skipped-nochange'
  | 'blocked-drift'
  | 'awaiting-provenance'
  | 'provenance-incomplete'
  | 'failed'

export interface DatasetOutcome {
  dataset_id: string
  version_before?: string
  version_after?: string
  status: DatasetOutcomeStatus
  reason?: string
  duration_ms: number
}

export interface PipelineRunSummary {
  datasets_total: number
  datasets_published: number
  datasets_skipped_nochange: number
  datasets_blocked_by_drift: number
  datasets_failed: number
  discovered_files_new: number
  schema_drift_opened: number
}

export interface PipelineRun {
  triggered_by: 'drive-change' | 'manual-dispatch' | 'schedule' | 'dataset-rerun'
  triggered_by_ip_hash?: string
  started_at: Timestamp
  ended_at?: Timestamp
  duration_ms?: number
  github_run_url: string
  status: PipelineRunStatus
  summary: PipelineRunSummary
  dataset_outcomes: DatasetOutcome[]
  drift_opened: string[]
  discovered_new: string[]
  error_summary?: string
}

export interface Provenance {
  source: string
  source_url: string | null
  license: string
  citation: string
  upstream_paths: string[]
}
`
  writeFileSync(join(DEST_ROOT, 'lib-data-types.ts'), shim, 'utf-8')
}

function main() {
  // Fresh start
  if (existsSync(DEST_ROOT)) rmSync(DEST_ROOT, { recursive: true, force: true })
  mkdirSync(DEST_ROOT, { recursive: true })

  // Shim first so the rewritten imports resolve
  copyLibDataTypesShim()

  for (const file of MODULES_TO_COPY) {
    const srcPath = join(SRC_ROOT, file)
    if (!existsSync(srcPath)) {
      console.warn(`  skipping missing source: ${srcPath}`)
      continue
    }
    const destPath = join(DEST_ROOT, file)
    copyFileWithRewrite(srcPath, destPath)
    console.log(`  synced ${file}`)
  }

  console.log(`\nSync complete → functions/src/shared/ (${MODULES_TO_COPY.length} modules)`)
}

main()
